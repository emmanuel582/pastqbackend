import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import express from 'express';
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'pastq-report-api-'));
process.env.DATA_DIR=temp;
process.env.AUTH_DISABLED_FOR_LOCAL_DEVELOPMENT='true';
const {saveBundle,getBundle}=await import('../services/library/store.js');
const {closeQuestionReports}=await import('../services/library/questionReports.js');
const {default:router}=await import('../routes/questionReports.js');
const app=express();app.use(express.json());app.use('/reports',router);
const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
const base=`http://127.0.0.1:${server.address().port}/reports`;
test.after(async()=>{await new Promise(resolve=>server.close(resolve));closeQuestionReports();fs.rmSync(temp,{recursive:true,force:true});});
test('human corrections reject stale reviews, reconcile rich text and publish a new download version',async()=>{
 const original={id:'q1',subject:'Biology',year:'2020',question:'Original wording',questionHtml:'<p>Original wording</p>',options:['A','B'],correct:0,explanation:'Original explanation',explanationHtml:'<p>Original explanation</p>'};
 saveBundle({id:'report-bank',title:'Biology',questions:[original]});
 const request=(url,method,body)=>fetch(base+url,{method,headers:{'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});
 const sent=await request('','POST',{id:'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee',bundleId:'report-bank',questionId:'q1',version:getBundle('report-bank').updated_at,category:'wording',note:'Please review wording'});assert.equal(sent.status,200);
 const row=(await(await request('/admin','GET')).json()).items[0];assert.ok(row.owner);
 const source=await(await request(`/admin/${row.id}/source?owner=${row.owner}`,'GET')).json();
 const body={owner:row.owner,status:'corrected',resolution:'Checked original source.',expectedVersion:'stale',edit:{...source.question,question:'Corrected wording',explanation:'Reviewed worked steps',topic:'Cells'}};
 assert.equal((await request('/admin/'+row.id,'PATCH',body)).status,409);
 body.expectedVersion=String(source.version);
 const fixed=await request('/admin/'+row.id,'PATCH',body);assert.equal(fixed.status,200);
 const report=await fixed.json(),updated=getBundle('report-bank');assert.equal(report.status,'corrected');assert.equal(report.correctedVersion,updated.updated_at);assert.notEqual(source.version,updated.updated_at);
 assert.equal(updated.questions[0].questionHtml,'<p>Corrected wording</p>');assert.equal(updated.questions[0].explanationHtml,'<p>Reviewed worked steps</p>');assert.equal(updated.questions[0].topic,'Cells');
 assert.equal(source.question.question,'Original wording');assert.equal((await request('/admin/'+row.id,'PATCH',body)).status,409);
});
